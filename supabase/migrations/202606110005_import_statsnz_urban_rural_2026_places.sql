insert into public.location_scopes (
  slug,
  name,
  scope_type,
  subtitle,
  source,
  source_id,
  is_public,
  is_selectable,
  sort_priority
)
select
  seed.slug,
  seed.name,
  'place',
  seed.indicator_name || ' - Stats NZ Urban Rural 2026',
  'statsnz_urban_rural_2026',
  seed.source_id,
  true,
  true,
  seed.sort_priority
from pcc_statsnz_urban_rural_2026_seed seed
on conflict (slug)
do update set
  name = excluded.name,
  subtitle = coalesce(public.location_scopes.subtitle, excluded.subtitle),
  source = case
    when public.location_scopes.source = 'manual' then public.location_scopes.source
    else excluded.source
  end,
  source_id = coalesce(public.location_scopes.source_id, excluded.source_id),
  is_public = true,
  is_selectable = true,
  sort_priority = least(public.location_scopes.sort_priority, excluded.sort_priority),
  updated_at = now()
where public.location_scopes.scope_type = 'place';

insert into public.location_aliases (
  location_scope_id,
  alias,
  source
)
select
  ls.id,
  seed.ascii_name,
  'statsnz_urban_rural_2026'
from pcc_statsnz_urban_rural_2026_seed seed
join public.location_scopes ls on ls.slug = seed.slug
where public.location_normalize(seed.ascii_name) <> public.location_normalize(seed.name)
  and ls.scope_type = 'place'
on conflict (location_scope_id, normalized_alias) do nothing;

insert into public.location_scope_links (
  child_scope_id,
  parent_scope_id,
  relationship_type,
  sort_order
)
select
  child.id,
  parent.id,
  'widens_to',
  200
from pcc_statsnz_urban_rural_2026_seed seed
join public.location_scopes child on child.slug = seed.slug
join public.location_scopes parent on parent.slug = 'new-zealand'
where child.scope_type = 'place'
  and not exists (
  select 1
  from public.location_scope_links existing
  where existing.child_scope_id = child.id
    and existing.relationship_type = 'widens_to'
)
on conflict (child_scope_id, parent_scope_id, relationship_type) do nothing;

