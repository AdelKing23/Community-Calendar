-- Remove the generic fallback created by the first official import where we now
-- have a proper regional parent. This keeps the visible ladder simple.
delete from public.location_scope_links existing
using pcc_statsnz_place_region_links seed,
  public.location_scopes child,
  public.location_scopes fallback_parent
where child.slug = seed.place_slug
  and child.source = 'statsnz_urban_rural_2026'
  and child.scope_type = 'place'
  and fallback_parent.slug = 'new-zealand'
  and existing.child_scope_id = child.id
  and existing.parent_scope_id = fallback_parent.id
  and existing.relationship_type = 'widens_to';

insert into public.location_scope_links (
  child_scope_id,
  parent_scope_id,
  relationship_type,
  sort_order
)
select
  child.id,
  parent.id,
  'widens_to',
  100
from pcc_statsnz_place_region_links seed
join public.location_scopes child on child.slug = seed.place_slug
join public.location_scopes parent on parent.slug = seed.region_slug
where child.source = 'statsnz_urban_rural_2026'
  and child.scope_type = 'place'
  and parent.scope_type = 'region'
on conflict (child_scope_id, parent_scope_id, relationship_type)
do update set sort_order = excluded.sort_order;

